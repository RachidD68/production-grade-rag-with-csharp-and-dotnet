using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace RagInDotNet.Tools.GenerateDataset;

internal enum DatasetSize { Small, Large }

/// <summary>Orchestrates synthetic-corpus generation across the six Contoso silos.</summary>
internal static class DatasetGenerator
{
    // Silo counts for --small (300 total). The 6th silo — Release Notes & Tickets —
    // exists for Ch 22 (freshness, drift, model migration) and is not in the
    // pre-revision project specification.
    private static readonly (string Folder, string DisplayName, int Count, Func<Random, int, SyntheticDocument> Generate)[] Silos =
    {
        ("hr-policies",            "HR Policies",                 40,  SiloContent.HrPolicy),
        ("technical-docs",         "Technical Docs",              120, SiloContent.TechnicalDoc),
        ("financial-reports",      "Financial Reports",           30,  SiloContent.FinancialReport),
        ("legal-contracts",        "Legal Contracts",             50,  SiloContent.LegalContract),
        ("product-catalog",        "Product Catalog",             30,  SiloContent.ProductCatalog),
        ("release-notes-tickets",  "Release Notes & Tickets",     30,  SiloContent.ReleaseNoteOrTicket),
    };

    public static int Run(int seed, DirectoryInfo output, DatasetSize size)
    {
        if (size != DatasetSize.Small)
        {
            throw new NotImplementedException("Only --small is implemented in Phase 0.");
        }

        var stopwatch = System.Diagnostics.Stopwatch.StartNew();
        Console.WriteLine($"generate-dataset --small (seed={seed}) -> {output.FullName}");

        // Determinism: derive a sub-seed per silo from the master seed so file order
        // within a silo doesn't shift if we ever change another silo's count.
        int totalProduced = 0;
        var manifestEntries = new List<(string RelativePath, string Sha256)>();

        foreach (var silo in Silos)
        {
            var siloDir = new DirectoryInfo(Path.Combine(output.FullName, silo.Folder));
            siloDir.Create();

            // Seed is masterSeed XOR siloFolder.GetHashCode (stable across runs because
            // we use a deterministic hash, not String.GetHashCode which varies by process).
            var siloSeed = unchecked(seed ^ DeterministicHash(silo.Folder));
            var rng = new Random(siloSeed);

            for (int i = 1; i <= silo.Count; i++)
            {
                var doc = silo.Generate(rng, i);
                var fileName = $"{silo.Folder}-{i:D3}.md";
                var filePath = Path.Combine(siloDir.FullName, fileName);

                var bytes = Encoding.UTF8.GetBytes(doc.Render());
                File.WriteAllBytes(filePath, bytes);

                var hash = Convert.ToHexStringLower(SHA256.HashData(bytes));
                var rel = Path.Combine(silo.Folder, fileName).Replace('\\', '/');
                manifestEntries.Add((rel, hash));
                totalProduced++;
            }

            Console.WriteLine($"  [{silo.DisplayName,-26}] {silo.Count,3} files");
        }

        // Manifest. Sort to guarantee stable ordering regardless of FS enumeration.
        manifestEntries.Sort((a, b) => string.CompareOrdinal(a.RelativePath, b.RelativePath));
        var manifestPath = Path.Combine(output.FullName, "manifest.sha256");
        var manifestBuilder = new StringBuilder();
        manifestBuilder.AppendLine(CultureInfo.InvariantCulture, $"# Generated by generate-dataset --small --seed {seed}");
        manifestBuilder.AppendLine(CultureInfo.InvariantCulture, $"# {totalProduced} files across {Silos.Length} silos");
        foreach (var (rel, hash) in manifestEntries)
        {
            manifestBuilder.Append(hash).Append("  ").Append(rel).Append('\n');
        }
        File.WriteAllText(manifestPath, manifestBuilder.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

        stopwatch.Stop();
        Console.WriteLine();
        Console.WriteLine($"✓ {totalProduced} files in {stopwatch.Elapsed.TotalSeconds:F2}s");
        Console.WriteLine($"  manifest: {manifestPath}");
        return 0;
    }

    // FNV-1a 32-bit. Stable across .NET versions and processes.
    private static int DeterministicHash(string s)
    {
        const uint offset = 2166136261;
        const uint prime = 16777619;
        uint h = offset;
        foreach (char c in s)
        {
            h ^= c;
            h *= prime;
        }
        return unchecked((int)h);
    }
}

/// <summary>One synthetic document — front-matter metadata + Markdown body.</summary>
internal sealed record SyntheticDocument(
    string Id,
    string Silo,
    string Department,
    string Office,
    string ConfidentialityLevel,
    string DocumentType,
    int FiscalYear,
    string Author,
    DateOnly LastModified,
    string Title,
    string Body)
{
    public string Render()
    {
        var sb = new StringBuilder();
        sb.Append("---\n");
        sb.Append(CultureInfo.InvariantCulture, $"id: {Id}\n");
        sb.Append(CultureInfo.InvariantCulture, $"silo: {Silo}\n");
        sb.Append(CultureInfo.InvariantCulture, $"department: {Department}\n");
        sb.Append(CultureInfo.InvariantCulture, $"office: {Office}\n");
        sb.Append(CultureInfo.InvariantCulture, $"confidentialityLevel: {ConfidentialityLevel}\n");
        sb.Append(CultureInfo.InvariantCulture, $"documentType: {DocumentType}\n");
        sb.Append(CultureInfo.InvariantCulture, $"fiscalYear: {FiscalYear}\n");
        sb.Append(CultureInfo.InvariantCulture, $"author: {Author}\n");
        sb.Append(CultureInfo.InvariantCulture, $"lastModified: {LastModified:yyyy-MM-dd}\n");
        sb.Append(CultureInfo.InvariantCulture, $"title: {Title}\n");
        sb.Append("---\n\n");
        sb.Append(CultureInfo.InvariantCulture, $"# {Title}\n\n");
        sb.Append(Body);
        if (!Body.EndsWith('\n'))
        {
            sb.Append('\n');
        }
        return sb.ToString();
    }
}
